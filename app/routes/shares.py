@router.delete("/share/{share_id}", tags=["share"])
@limiter.limit("30/minute")
def delete_share(request: Request, share_id: str, auth: Auth = Depends(verify_token)):
    """
    Permanently delete a shared space and all its files. Owner only.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_owner(share, auth.username)

    for username in share.get("members", {}):
        _update_user_share_index(username, auth.app, share_id, add=False)

    shutil.rmtree(share_path)
    return {"message": messages.shareDeleted}


@router.post("/share-code", tags=["share"])
@limiter.limit("10/minute")
def create_share_code(request: Request, auth: Auth = Depends(verify_token)):
    """
    Generate a one-time share code for the authenticated user.

    The user sends this code to a share owner out-of-band. The owner redeems
    it via `POST /share/{share_id}/member` to add the user to a share, which
    consumes the code. Codes expire after 24 hours.

    The response includes a `fingerprint` of the caller's public key, pinned
    into the code at creation time. The invitee must send this fingerprint to
    the owner over the same trusted out-of-band channel as the code. The owner
    verifies it against the key it wraps the share key with, so the server
    cannot substitute its own key to intercept the share key. Clients should
    recompute the fingerprint locally (`SHA256` of the public key string)
    rather than trusting the value the server returns here.

    **Authentication Required**: Yes (via headers)

    **Response**:
    ```json
    {
        "code": "one-time-share-code",
        "fingerprint": "sha256-hex-of-public-key",
        "expires_at": 1789000000
    }
    ```
    """
    code = str(uuid.uuid4())
    code_file = get_share_code_path(code, auth.app)
    code_file.parent.mkdir(parents=True, exist_ok=True)
    created_at = get_utc_timestamp()

    user_file = get_user_data_path(auth.username, auth.app) / FILE_PATH_USER
    with open(user_file) as f:
        public_key = json.load(f).get(UserField.PUBLIC_KEY)
    fingerprint = _fingerprint(public_key)

    write_json(code_file, {
        "username": auth.username,
        "created_at": created_at,
        "public_key": public_key,
        "fingerprint": fingerprint,
    })
    return {"code": code, "fingerprint": fingerprint, "expires_at": created_at + SHARE_CODE_TTL_SECONDS}


@router.get("/share-code/{code}", tags=["share"])
@limiter.limit("30/minute")
def resolve_share_code(request: Request, code: str, auth: Auth = Depends(verify_token)):
    """
    Resolve a share code to the user who generated it, with their public key.

    The share owner calls this to wrap the share key for the code's user
    before redeeming the code via `POST /share/{share_id}/member`. Resolving
    does not consume the code - only redeeming it does.

    The `public_key` and `fingerprint` are the values pinned when the invitee
    created the code, not a live (swappable) copy from the user's profile. The
    owner MUST compare this `fingerprint` against the one received from the
    invitee out-of-band before wrapping the share key; a mismatch means the key
    is not authentic and the owner must abort.

    **Response**:
    ```json
    {
        "username": "bob",
        "public_key": "user_public_key_string",
        "fingerprint": "sha256-hex-of-public-key"
    }
    ```
    """
    code_file, code_data = _resolve_share_code(code, auth.app)
    return {
        "username": code_data.get("username"),
        "public_key": code_data.get("public_key"),
        "fingerprint": code_data.get("fingerprint"),
    }


@router.post("/share/{share_id}/member", tags=["share"])
@limiter.limit("30/minute")
def add_member(request: Request, share_id: str, req: ShareMemberRequest, auth: Auth = Depends(verify_token)):
    """
    Add a member to a shared space by redeeming their one-time share code.
    Owner only. Consumes the code.

    **Request Body** (JSON):
    ```json
    {
        "code": "one-time-share-code-from-the-member",
        "encrypted_key": "share_key_wrapped_with_members_public_key",
        "public_key_fingerprint": "sha256-hex-of-the-key-you-wrapped-for",
        "role": "write"
    }
    ```

    **Client-side flow**:
    1. Receive a share code AND the key fingerprint from the user, out-of-band
    2. Resolve the code to their public key via `GET /share-code/{code}`
    3. Verify the resolved key's fingerprint equals the one received in step 1;
       abort on mismatch (the server may be substituting a key)
    4. Encrypt (wrap) the share key with the verified public key
    5. Send the code, the wrapped key, and the verified fingerprint - the code
       is consumed on success

    The server rejects the request unless `public_key_fingerprint` matches the
    key pinned when the code was created, binding the wrapped key to a specific,
    out-of-band-verified public key.

    **Roles**: `write` (read and modify files) or `read` (read-only).
    """
    if req.role not in (ROLE_WRITE, ROLE_READ):
        raise HTTPException(status_code=422, detail=messages.somethingWentWrong)

    with _edit_share(share_id, auth.app) as share:
        _require_owner(share, auth.username)

        code_file, code_data = _resolve_share_code(req.code, auth.app)
        username = code_data.get("username")
        pinned_fingerprint = code_data.get("fingerprint")

        if not pinned_fingerprint or req.public_key_fingerprint != pinned_fingerprint:
            raise HTTPException(status_code=400, detail=messages.publicKeyMismatch)

        if username in share.get("members", {}):
            raise HTTPException(status_code=400, detail=messages.alreadyShareMember)

        member_file = get_user_data_path(username, auth.app) / FILE_PATH_USER
        if not member_file.exists():
            raise HTTPException(status_code=404, detail=messages.userNotFound)

        share["members"][username] = {
            "role": req.role,
            "encrypted_key": req.encrypted_key,
            "public_key_fingerprint": pinned_fingerprint,
            "added_at": get_utc_timestamp(),
        }
    _update_user_share_index(username, auth.app, share_id, add=True)
    code_file.unlink(missing_ok=True)
    return {"message": messages.memberAdded, "username": username}


@router.delete("/share/{share_id}/member/{username}", tags=["share"])
@limiter.limit("30/minute")
def remove_member(request: Request, share_id: str, username: str, auth: Auth = Depends(verify_token)):
    """
    Remove a member from a shared space.

    The owner can remove any member; a member can remove themselves (leave).
    The owner cannot be removed - delete the share instead.

    **Security note**: a removed member has had access to the share key.
    After removal the owner's client should rotate: generate a new share key,
    re-encrypt the share's files, and upload re-wrapped keys via
    `PUT /share/{share_id}/keys`.
    """
    with _edit_share(share_id, auth.app) as share:
        if auth.username != username:
            _require_owner(share, auth.username)

        if username == share.get("owner"):
            raise HTTPException(status_code=400, detail=messages.notShareMember)
        if username not in share.get("members", {}):
            raise HTTPException(status_code=404, detail=messages.memberNotFound)

        del share["members"][username]
    _update_user_share_index(username, auth.app, share_id, add=False)
    return {"message": messages.memberRemoved}


@router.put("/share/{share_id}/keys", tags=["share"])
@limiter.limit("30/minute")
def rotate_share_keys(request: Request, share_id: str, req: ShareKeysRequest, auth: Auth = Depends(verify_token)):
    """
    Replace the wrapped share key for every member (key rotation). Owner only.

    Used after removing a member: the owner's client generates a new share
    key, re-encrypts the share's files with it, wraps the new key with each
    remaining member's public key, and uploads all wrapped keys here.

    **Request Body** (JSON):
    ```json
    {
        "keys": {
            "alice": "new_key_wrapped_with_alices_public_key",
            "bob": "new_key_wrapped_with_bobs_public_key"
        }
    }
    ```

    The `keys` map must contain exactly the current members of the share.
    """
    with _edit_share(share_id, auth.app) as share:
        _require_owner(share, auth.username)

        members = share.get("members", {})
        if set(req.keys.keys()) != set(members.keys()):
            raise HTTPException(status_code=400, detail=messages.missingMemberKeys)

        for username, encrypted_key in req.keys.items():
            members[username]["encrypted_key"] = encrypted_key
        share["key_rotated_at"] = get_utc_timestamp()
    return {"message": messages.shareKeysUpdated}


@router.post("/share/{share_id}/file/{folder}/{filename}", tags=["share"])
@limiter.limit("120/minute")
def save_share_file(
        request: Request,
        share_id: str,
        folder: str,
        filename: str,
        data: str = Body(..., media_type="text/plain"),
        auth: Auth = Depends(verify_token)
):
    """
    Save or overwrite a file in a shared space (content encrypted client-side
    with the share key). Requires write access. Counts against the owner's
    storage quota.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_member(share, auth.username, write=True)

    file_location = _resolve_share_file_path(share_path, folder, filename)
    _check_share_storage_limit(share_path, share, auth.app, len(data.encode("utf-8")))

    file_location.parent.mkdir(parents=True, exist_ok=True)
    with open(file_location, "w", encoding="utf-8") as f:
        f.write(data)
    return {"message": messages.fileSaved}


