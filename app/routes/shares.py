@router.get("/share/{share_id}/files/{folder:path}/index", tags=["share"])
@limiter.limit("60/minute")
def get_share_files_index(
        request: Request,
        share_id: str,
        folder: str,
        auth: Auth = Depends(verify_token)
):
    """
    List file names and modification times in a shared-space folder,
    without content. Any member can read.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_member(share, auth.username)

    folder_path = _resolve_share_file_path(share_path, folder)
    if not folder_path.exists() or not folder_path.is_dir():
        return {"files": []}

    files = [
        {"name": f.name, "time": int(f.stat().st_mtime)}
        for f in folder_path.iterdir() if f.is_file()
    ]
    files.sort(key=lambda f: f["time"], reverse=True)
    return {"files": files}


@router.get("/share/{share_id}/files/{folder:path}", tags=["share"])
@limiter.limit("60/minute")
def get_share_files(
        request: Request,
        share_id: str,
        folder: str,
        start: int = Query(0, ge=0),
        limit: int = Query(100, ge=1, le=1000),
        reverse: bool = Query(False),
        newer_than: Optional[int] = Query(None),
        auth: Auth = Depends(verify_token)
):
    """
    Paginated list of files with content from a shared-space folder.
    Same shape and parameters as `GET /files/{folder}`. Any member can read.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_member(share, auth.username)

    folder_path = _resolve_share_file_path(share_path, folder)
    if not folder_path.exists() or not folder_path.is_dir():
        return {"files": [], "total": 0, "start": start, "limit": limit, "has_more": False}

    all_files = [f for f in folder_path.iterdir() if f.is_file()]
    if newer_than is not None:
        all_files = [f for f in all_files if f.stat().st_mtime > newer_than]
    all_files_sorted = sorted(all_files, key=lambda f: f.stat().st_mtime, reverse=not reverse)
    total = len(all_files_sorted)

    end = start + limit
    files_with_content = []
    for file_path in all_files_sorted[start:end]:
        try:
            stat = file_path.stat()
            with open(file_path, "r", encoding="utf-8") as f:
                content = f.read()
            files_with_content.append({
                "name": file_path.name,
                "data": content,
                "time": int(stat.st_mtime)
            })
        except Exception as read_error:
            files_with_content.append({
                "name": file_path.name,
                "data": None,
                "error": f"Failed to read file: {str(read_error)}"
            })

    return {
        "files": files_with_content,
        "total": total,
        "start": start,
        "limit": limit,
        "has_more": end < total
    }


@router.post("/share/{share_id}/files/{folder:path}", tags=["share"])
@limiter.limit("30/minute")
def post_share_files(
        request: Request,
        share_id: str,
        folder: str,
        files: List[FileItem],
        auth: Auth = Depends(verify_token)
):
    """
    Save multiple files into a shared-space folder. Requires write access.
    Same shape as `POST /files/{folder}`.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_member(share, auth.username, write=True)

    folder_path = _resolve_share_file_path(share_path, folder)

    incoming_bytes = sum(len(f.data.encode("utf-8")) for f in files)
    _check_share_storage_limit(share_path, share, auth.app, incoming_bytes)

    folder_path.mkdir(parents=True, exist_ok=True)

    saved = []
    errors = []
    for file in files:
        if "/" in file.name or "\\" in file.name:
            errors.append({"name": file.name, "error": messages.invalidPath})
            continue
        try:
            (folder_path / file.name).write_text(file.data, encoding="utf-8")
            saved.append(file.name)
        except Exception as e:
            errors.append({"name": file.name, "error": str(e)})

    return {"saved": saved, "errors": errors}


@router.delete("/share/{share_id}/files/{folder:path}", tags=["share"])
@limiter.limit("30/minute")
def delete_share_files(
        request: Request,
        share_id: str,
        folder: str,
        req: FilesDeleteRequest,
        auth: Auth = Depends(verify_token)
):
    """
    Delete multiple files from a shared-space folder. Requires write access.
    Same shape as `DELETE /files/{folder}`.
    """
    share_path, share = _load_share(share_id, auth.app)
    _require_member(share, auth.username, write=True)

    folder_path = _resolve_share_file_path(share_path, folder)

    deleted = []
    errors = []
    for name in req.files:
        if "/" in name or "\\" in name:
            errors.append({"name": name, "error": messages.invalidPath})
            continue
        file_path = folder_path / name
        if not file_path.exists():
            deleted.append(name)
            continue
        try:
            file_path.write_bytes(b"")
            deleted.append(name)
        except Exception as e:
            errors.append({"name": name, "error": str(e)})

    return {"deleted": deleted, "errors": errors}
