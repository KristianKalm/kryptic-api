router = APIRouter()
limiter = Limiter(key_func=get_remote_address)

FILE_PATH_SHARE = "share.json"
FILE_PATH_USER_SHARES = "shares.json"
SHARE_FILES_DIR = "files"

ROLE_OWNER = "owner"
ROLE_WRITE = "write"
ROLE_READ = "read"

SHARE_CODE_TTL_SECONDS = 24 * 60 * 60


class ShareCreateRequest(BaseModel):
    name: Optional[str] = None  # opaque to the server, client may encrypt it
    encrypted_key: str  # share key wrapped with the owner's own public key


class ShareMemberRequest(BaseModel):
    code: str  # one-time share code generated by the member
    encrypted_key: str  # share key wrapped with the member's public key
    # Fingerprint of the public key the owner actually wrapped the share key
    # with. The owner obtains this fingerprint from the invitee out-of-band
    # (over the same trusted channel as the code) and the server binds the
    # redemption to the key pinned when the code was created. This prevents the
    # server from substituting its own public key to intercept the share key.
    public_key_fingerprint: str
    role: str = ROLE_WRITE


class ShareKeysRequest(BaseModel):
    keys: Dict[str, str]  # username -> share key wrapped with that member's public key


class FileItem(BaseModel):
    name: str
    data: str


class FilesDeleteRequest(BaseModel):
    files: List[str]


def _fingerprint(public_key: str) -> str:
    """Stable fingerprint of a public key, used to verify key authenticity
    out-of-band. Both the invitee and the owner hash the same key string, so a
    server that substitutes a different key produces a mismatching fingerprint."""
    return sha256((public_key or "").encode("utf-8")).hexdigest()


def _share_file(share_id: str, app: str) -> Path:
    try:
        uuid.UUID(share_id)
    except ValueError:
        raise HTTPException(status_code=400, detail=messages.invalidPath)
    share_file = get_share_data_path(share_id, app) / FILE_PATH_SHARE
    if not share_file.exists():
        raise HTTPException(status_code=404, detail=messages.shareNotFound)
    return share_file


def _load_share(share_id: str, app: str):
    share_file = _share_file(share_id, app)
    with open(share_file) as f:
        return share_file.parent, json.load(f)


@contextmanager
def _edit_share(share_id: str, app: str):
    """Locked read-modify-write on a share's metadata. Mutations to the
    yielded dict are persisted atomically on clean exit."""
    share_file = _share_file(share_id, app)
    with edit_json(share_file) as ref:
        yield ref.data


def _save_share(share_path: Path, share: dict):
    write_json(share_path / FILE_PATH_SHARE, share)


def _require_member(share: dict, username: str, write: bool = False) -> dict:
    member = share.get("members", {}).get(username)
    if member is None:
        raise HTTPException(status_code=403, detail=messages.notShareMember)
    if write and member.get("role") == ROLE_READ:
        raise HTTPException(status_code=403, detail=messages.readOnlyShareMember)
    return member


def _require_owner(share: dict, username: str):
    if share.get("owner") != username:
        raise HTTPException(status_code=403, detail=messages.notShareOwner)


def _resolve_share_code(code: str, app: str):
    try:
        uuid.UUID(code)
    except ValueError:
        raise HTTPException(status_code=400, detail=messages.invalidPath)
    code_file = get_share_code_path(code, app)
    if not code_file.exists():
        raise HTTPException(status_code=404, detail=messages.shareCodeNotFound)
    with open(code_file) as f:
        code_data = json.load(f)
    if get_utc_timestamp() > code_data.get("created_at", 0) + SHARE_CODE_TTL_SECONDS:
        code_file.unlink(missing_ok=True)
        raise HTTPException(status_code=410, detail=messages.shareCodeExpired)
    return code_file, code_data


def _update_user_share_index(username: str, app: str, share_id: str, add: bool):
    user_path = get_user_data_path(username, app)
    if not user_path.exists():
        return
    index_file = user_path / FILE_PATH_USER_SHARES
    with edit_json(index_file, default=[]) as ref:
        share_ids = ref.data
        if add and share_id not in share_ids:
            share_ids.append(share_id)
        if not add and share_id in share_ids:
            share_ids.remove(share_id)


def _member_view(share: dict, username: str) -> dict:
    """Share as seen by one member: their own wrapped key, other members without keys."""
    return {
        "id": share["id"],
        "name": share.get("name"),
        "owner": share["owner"],
        "created_at": share.get("created_at"),
        "role": share["members"][username].get("role"),
        "encrypted_key": share["members"][username].get("encrypted_key"),
        "members": [
            {
                "username": u,
                "role": m.get("role"),
                "added_at": m.get("added_at"),
                "public_key_fingerprint": m.get("public_key_fingerprint"),
            }
            for u, m in share.get("members", {}).items()
        ],
    }


def _check_share_storage_limit(share_path: Path, share: dict, app: str, incoming_bytes: int):
    """Shared space storage counts against the share owner's quota."""
    owner_path = get_user_data_path(share.get("owner"), app)
    max_mb = get_user_max_mb(owner_path, app)
    if max_mb is None:
        return
    if get_user_usage_bytes(share_path) + incoming_bytes > max_mb * 1024 * 1024:
        raise HTTPException(status_code=413, detail=messages.storageLimitExceeded)


def _resolve_share_file_path(share_path: Path, *parts: str) -> Path:
    files_base = (share_path / SHARE_FILES_DIR).resolve()
    target = files_base.joinpath(*parts).resolve()
    if not str(target).startswith(str(files_base) + "/"):
        raise HTTPException(status_code=400, detail=messages.invalidPath)
    return target


@router.post("/share", tags=["share"])
@limiter.limit("30/minute")
def create_share(request: Request, req: ShareCreateRequest, auth: Auth = Depends(verify_token)):
    """
    Create a new end-to-end encrypted shared space.

    **Authentication Required**: Yes (via headers)

    **Request Body** (JSON):
    ```json
    {
        "name": "family-vault",
        "encrypted_key": "share_key_wrapped_with_own_public_key"
    }
    ```

    **Client-side flow**:
    1. Generate a random symmetric share key
    2. Encrypt (wrap) it with your own public key
    3. Send only the wrapped key - the server never sees the plaintext key

    **Response**:
    ```json
    {
        "share": { "id": "...", "owner": "...", "role": "owner", ... }
    }
    ```
    """
    share_id = str(uuid.uuid4())
    share_path = get_share_data_path(share_id, auth.app)
    share_path.mkdir(parents=True)
    share = {
        "id": share_id,
        "name": req.name,
        "owner": auth.username,
        "created_at": get_utc_timestamp(),
        "members": {
            auth.username: {
                "role": ROLE_OWNER,
                "encrypted_key": req.encrypted_key,
                "added_at": get_utc_timestamp(),
            }
        },
    }
    _save_share(share_path, share)
    _update_user_share_index(auth.username, auth.app, share_id, add=True)
    return {"share": _member_view(share, auth.username)}


@router.get("/shares", tags=["share"])
@limiter.limit("60/minute")
def list_shares(request: Request, auth: Auth = Depends(verify_token)):
    """
    List all shared spaces the authenticated user owns or is a member of.

    Each entry includes the caller's own wrapped share key (`encrypted_key`),
    which the client decrypts locally with its private key.
    """
    user_path = get_user_data_path(auth.username, auth.app)
    index_file = user_path / FILE_PATH_USER_SHARES
    share_ids = []
    if index_file.exists():
        with open(index_file) as f:
            share_ids = json.load(f)

    shares = []
    for share_id in share_ids:
        share_file = get_share_data_path(share_id, auth.app) / FILE_PATH_SHARE
        if not share_file.exists():
            continue
        with open(share_file) as f:
            share = json.load(f)
        if auth.username in share.get("members", {}):
            shares.append(_member_view(share, auth.username))
    return {"shares": shares}


